// Rcon: Round Constants per rompere le simmetrie
static const unsigned char rcon[] = {0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36};

/**
 * @brief Inietta la chiave nel blocco di stato.
 */
void aes_add_round_key(unsigned char *state, unsigned char *round_key)
{
    for (int i = 0; i < 16; i++)
        state[i] ^= round_key[i];
}

/**
 * @brief Espansione della chiave: genera le round key successive.
 * (Snippet semplificato per Key Expansion a 128-bit)
 */
void aes_key_expansion(unsigned char *key, unsigned char *w)
{
    // Copia la chiave iniziale nei primi 16 byte
    for (int i = 0; i < 16; i++) w[i] = key[i];

    // Genera le restanti 160 byte (per 11 round totali)
    for (int i = 16; i < 176; i += 4) {
        unsigned char temp[4];
        for (int k = 0; k < 4; k++) temp[k] = w[i - 4 + k];
        
        if (i % 16 == 0) {
            // RotWord + SubWord + Rcon
            unsigned char t = temp[0];
            temp[0] = sbox[temp[1]] ^ rcon[(i/16)-1];
            temp[1] = sbox[temp[2]];
            temp[2] = sbox[temp[3]];
            temp[3] = sbox[t];
        }
        for (int k = 0; k < 4; k++) w[i + k] = w[i - 16 + k] ^ temp[k];
    }
}


/*
 * =====================================================================================
 * AES_KEY_EXPANSION E ADDROUNDKEY - IL MOTORE DEL CIFRARIO
 * =====================================================================================
 *
 * BACKGROUND TEORICO:
 * L'AES non usa la stessa chiave per ogni round. La "Key Expansion" trasforma la 
 * chiave master in un array di "Round Keys". Per AES-128, generiamo 11 chiavi da 16 byte.
 *
 * I TRE PASSAGGI DELLA KEY EXPANSION:
 * 1. RotWord: Rotazione ciclica dei byte di una parola (4 byte).
 * 2. SubWord: Applicazione della S-Box (stessa di SubBytes) ai 4 byte.
 * 3. Rcon: XOR con la Round Constant (per rompere le simmetrie).
 *
 * ADDROUNDKEY (Il Quarto Mattone):
 * È l'operazione che "inieetta" la RoundKey nel blocco di stato. Si esegue 
 * tramite un semplice XOR byte-a-byte. Senza questa, il cifrario sarebbe 
 * vulnerabile a semplici attacchi algebrici.
 *
 * APPLICAZIONI PRATICHE:
 * La Key Expansion garantisce che la sicurezza non dipenda solo dalla chiave master,
 * ma da una sequenza di chiavi correlate ma crittograficamente distinte.
 *
 * IMPLEMENTAZIONE HARDWARE:
 * La Key Expansion è spesso pre-calcolata e memorizzata in una RAM dedicata 
 * (Key Buffer) per non rallentare la pipeline di cifratura.
 

 * BACKGROUND TEORICO SULLA S-BOX:
 * La S-Box AES è il cuore della non-linearità del cifrario. Non è una tabella casuale,
 * ma deriva da due passaggi matematici precisi nel campo di Galois GF(2^8):
 * 1. Inverso moltiplicativo: Ogni byte viene sostituito dal suo inverso nel campo 
 * GF(2^8), che è una funzione altamente non lineare.
 * 2. Trasformazione Affine: Viene applicata una matrice di trasformazione bit-a-bit 
 * seguita da un XOR con la costante 0x63. Questo serve a "rompere" le relazioni 
 * algebriche semplici, rendendo la S-Box resistente alla crittoanalisi algebrica.
 * Senza questa S-Box, l'intero AES sarebbe riducibile a un sistema di equazioni 
 * lineari facilmente risolvibile.
 *
 * KEY EXPANSION E ADDROUNDKEY:
 * La Key Expansion genera le Round Keys per i 10 round successivi. L'AddRoundKey 
 * è l'operazione di "iniezione" che usa lo XOR per legare la chiave allo stato, 
 * garantendo che ogni round sia dipendente dalla chiave master.
 * =====================================================================================
 */



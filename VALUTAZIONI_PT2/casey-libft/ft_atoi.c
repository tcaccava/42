#include "libft.h"

int	ft_atoi(const char *str)
{
	int	j;
	int	k;
	int	res;

	j = 0;
	k = 1;
	res = 0;
	while (str[j] == ' ' || (str[j] >= 9 && str[j] <= 13))
		j++;
	if (str[j] == '+' || str[j] == '-')
	{
		if (str[j] == '-')
			k = -k;
		j++;
	}
	while (str[j] >= 48 && str[j] <= 57)
	{
		res = res * 10 + (str[j] - '0');
		j++;
	}
	return (res * k);
}

#include "libft.h"

void	*ft_memset(void *s, int c, size_t len)
{
	unsigned char	*p2;

	p2 = (unsigned char *)s;
	while (len > 0)
	{
		*p2 = c;
		p2++;
		len--;
	}
	return (s);
}
